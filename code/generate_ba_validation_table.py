"""Generate the manuscript validation table from the recorded runs."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
records=[json.loads((ROOT/'code/results'/f'{kind}_sigma_ba.json').read_text())
         for kind in ['hyperelliptic','trigonal']]
def tex(value):
    mantissa,exponent=f'{value:.1e}'.split('e')
    mantissa=float(mantissa);exponent=int(exponent)
    return f'${mantissa:.1f}\\times10^{{{exponent}}}$'
rows=[('Mode discrepancy','fine_ode_error'),('Mode-power discrepancy','fine_modal_power_error'),
      ('Canonical vector-field residual','all_mode_canonical_residual'),
      ('BA conserved-quantity drift','BA_conserved_quantity_drift'),
      ('Runge--Kutta conserved-quantity drift','ODE_conserved_quantity_drift')]
lines=[r'% Generated by code/generate_ba_validation_table.py from recorded JSON.',
       r'\begin{center}',r'\begin{tabular}{lcc}',r'\hline',
       r'Check & Hyperelliptic & Trigonal\\',r'\hline']
for title,key in rows:lines.append(title+' & '+' & '.join(tex(r[key]) for r in records)+r'\\')
diagnostics=[json.loads((ROOT/'code/results'/f'{kind}_convergence_diagnostic.json').read_text())
             for kind in ['hyperelliptic','trigonal']]
ratios=[d['multiprecision'][1]['step_halving_difference']/
        d['multiprecision'][2]['step_halving_difference'] for d in diagnostics]
lines.append('35-digit RK4 refinement ratio & '+' & '.join(f'${r:.1f}$' for r in ratios)+r'\\')
lines.append('Extrapolated mode discrepancy & '+' & '.join(
    tex(d['multiprecision_Richardson_BA_discrepancy']) for d in diagnostics)+r'\\')
lines += [r'\hline',r'\end{tabular}',r'\end{center}']
(ROOT/'latex/ba-validation-table.tex').write_text('\n'.join(lines)+'\n')
print('Updated validation table from recorded results')

def complex_tex(pair):
    real,imag=pair
    return f'${real:.6f}{imag:+.6f}i$'

trigonal=records[1]
lines=[r'% Generated from code/results/trigonal_sigma_ba.json.',
       r'\begin{center}',r'\begin{tabular}{ccc}',r'\hline',
       r'$k$ & $\kappa_k$ & $b_k$\\',r'\hline']
for k,(weight,phase) in enumerate(zip(trigonal['normalized_residue_weights'],
                                     trigonal['phase_coefficients']),1):
    lines.append(f'{k} & {complex_tex(weight)} & {complex_tex(phase)}'+r'\\')
lines += [r'\hline',r'\end{tabular}',r'\end{center}']
(ROOT/'latex/ba-trigonal-parameters.tex').write_text('\n'.join(lines)+'\n')
print('Updated trigonal parameters from recorded results')
